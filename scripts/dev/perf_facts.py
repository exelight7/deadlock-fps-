"""Generate (or check) deadlock_fps/perf/facts.py: facts about every setting the Toolbox recipe can write, taken from Valve's data.
Usage: perf_facts.py <repo root> <catalogue.json> [--check]

The catalogue is a JSON file that carries Valve's public convar dump and the history of Valve's stock gameinfo.gi (the
community reference app ships one as `packages/perf-catalog/data/catalog.json`; it is GPL-3.0, so it is read here and
never copied into this repository). Only facts about Valve's game are taken from it: a setting's name, its flags,
its default value, and whether Valve still has it. No text of the catalogue is kept.

Statuses: active (Valve lists it and nothing blocks it), removed (Valve's dump no longer has it), blocked (flagged
gameinfo_cannot_override: Valve does not let gameinfo.gi change it), cheat (flagged cheat: whether gameinfo.gi may
change it is not documented), unverified (not in Valve's data at all).

With --check nothing is written: the script prints every difference between the file and the catalogue (use it after
a game update, or with a newer catalogue, to see what changed).
"""
import json
import sys
from datetime import date
from pathlib import Path

repo, catalogue_path = Path(sys.argv[1]), Path(sys.argv[2])
check = '--check' in sys.argv
sys.path.insert(0, str(repo))
from deadlock_fps.settings import Settings, values, MAX_LEVEL

catalogue = json.loads(catalogue_path.read_text(encoding='utf-8'))
convars = {c['name'].lower(): c for c in catalogue['convars']}
stock = sorted(catalogue['stock'], key=lambda b: b['build'])
newest = stock[-1]

# every setting any slider position can write, by where it is written
written = {'convar': set(), 'video': set(), 'scene': set()}
for level in range(MAX_LEVEL + 1):
    for aspect in (None, 2.0):
        for cpu in (True, False):
            s = Settings.at_level(level, aspect_ratio=aspect)
            s.cpu = cpu
            video, cv, scene = values(s)
            written['convar'].update(cv)
            written['video'].update(k.removeprefix('setting.') for k in video)
            written['scene'].update(scene)
names = {'convar': written['convar'], 'video': written['video'] - written['convar'], 'scene': written['scene']}


def convar_fact(name):
    entry = convars.get(name.lower())
    if entry is None:
        return 'unverified', 0, ''
    flags = entry.get('flags') or []
    default = '' if entry.get('default') is None else str(entry['default'])
    if entry.get('status') == 'removed':
        return 'removed', int(entry.get('statusSinceBuild') or 0), default
    if 'gameinfo_cannot_override' in flags:
        return 'blocked', 0, default
    if 'cheat' in flags:
        return 'cheat', 0, default
    return 'active', 0, default


def scene_fact(name):
    def holds(build):
        return next((e['value'] for e in build['entries'] if len(e['path']) == 2 and e['path'][0].lower() == 'scenesystem' and e['path'][1].lower() == name.lower()), None)
    present = [(b['build'], holds(b)) for b in stock if holds(b) is not None]
    if not present:
        return 'unverified', 0, ''
    if present[-1][0] == newest['build']:
        return 'active', 0, str(present[-1][1])
    later = [b['build'] for b in stock if b['build'] > present[-1][0]]
    return 'removed', later[0] if later else 0, str(present[-1][1])


facts = {}
for name in sorted(names['convar'] | names['video']):
    facts[name] = convar_fact(name)
for name in sorted(names['scene']):
    facts[name] = scene_fact(name)

lines = ['"""Facts about every setting the Toolbox recipe can write, checked against Valve\'s public data.',
         '',
         'GENERATED by scripts/dev/perf_facts.py. Do not edit by hand: change the recipe or run the script again.',
         'Only names, Valve\'s flags and default values: facts about Valve\'s game. The explanations are in knowledge.py.',
         '',
         'status: active | removed | blocked | cheat | unverified (see the script for what each one means).',
         'since: the build in which Valve stopped listing it (0 when unknown). default: Valve\'s own default value.',
         '"""',
         'CONVAR_BUILD = %d          # the build of the convar dump' % int(catalogue['convarBuild']),
         'STOCK_BUILD = %d           # the newest stock gameinfo.gi that was compared' % int(newest['build']),
         "CHECKED_ON = '%s'" % date.today().isoformat(),
         '',
         '# name: (status, since, default)',
         'FACTS = {']
for name, (status, since, default) in facts.items():
    lines.append('    %r: (%r, %d, %r),' % (name, status, since, default))
lines += ['}', '']
generated = '\n'.join(lines)

target = repo / 'deadlock_fps' / 'perf' / 'facts.py'
if check:
    current = target.read_bytes().decode('utf-8') if target.exists() else ''
    import re
    parse = lambda text: {m[0]: m[1:] for m in re.findall(r"^    '([^']+)': \('(\w+)', (\d+), '([^']*)'\),$", text, re.M)}
    old, new = parse(current), parse(generated)
    changed = [(k, old.get(k), new.get(k)) for k in sorted(set(old) | set(new)) if old.get(k) != new.get(k)]
    print('settings in the file: %d, in a fresh generation: %d' % (len(old), len(new)))
    print('differences: %s' % ('none: the file agrees with the catalogue' if not changed else ''))
    for item in changed:
        print('  %s: file %s -> catalogue %s' % item)
    sys.exit(1 if changed else 0)
target.parent.mkdir(parents=True, exist_ok=True)
target.write_bytes(generated.encode('utf-8'))           # bytes: the repository is LF
counts = {}
for status, _, _ in facts.values():
    counts[status] = counts.get(status, 0) + 1
print('wrote %s: %d settings %s' % (target.relative_to(repo), len(facts), counts))
